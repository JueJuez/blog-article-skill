def get_note_prompt(note_type: str = "structured") -> str:
    """按笔记类型取对应的总结 Prompt 模板。

    未知类型安全回退到 structured。
    """
    t = NOTE_TEMPLATES.get(note_type)
    if not t:
        t = NOTE_TEMPLATES["structured"]
    return t["prompt"]


def list_note_types():
    """列出所有可用笔记类型（key / 名称 / 说明）。"""
    return [
        {"key": k, "name": v["name"], "desc": v["desc"]}
        for k, v in NOTE_TEMPLATES.items()
    ]


def format_note_with_prompt(content: str, author: str = "", url: str = "", tags: list = None, add_metadata: bool = True) -> str:
    """格式化笔记内容
    
    Args:
        content: 笔记正文内容
        author: 作者信息
        url: 原文链接
        tags: 标签列表
        add_metadata: 是否添加元数据（标签、作者、链接）
    
    Returns:
        格式化后的笔记内容
    """
    tags = tags or []
    
    if add_metadata:
        # 添加标签
        if tags:
            formatted = "#" + " #".join(tags) + "\n\n"
        else:
            formatted = ""

        # 添加作者和来源链接（格式：**作者**：xxx | **来源链接**：[原文链接](URL)）
        author_display = author if author else "【作者未知】"
        if url:
            formatted += f"**作者**：{author_display} | **来源链接**：[原文链接]({url})\n\n"
        else:
            formatted += f"**作者**：{author_display} | **来源链接**：【无来源链接】\n\n"

        formatted += content
    else:
        formatted = content

    return formatted
