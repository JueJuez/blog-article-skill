def render_coverage_guide(source_chars: int, note_type: str = "structured") -> str:
    """保留输入长度提示，取消比例目标；覆盖由要点与证据核对。"""
    if not source_chars or source_chars < 400:
        return ""
    lines = [
        "", "",
        "# 附：本篇输入范围与覆盖检查",
        "",
        f"- 源长：约 **{source_chars}** 字",
        "- 输入长度不等于有效信息量，不据此规定目标字数、比例下限或上限。",
        "- 对照源的要点、步骤、条件、限制、数字口径和资源入口检查；先补遗漏，再去重复表达。",
        "- 不因短而判缺、不因长而判照搬；覆盖优先于字数，语义判断不能由比例替代。",
    ]
    return chr(10).join(lines)


def get_note_prompt(note_type: str = "structured", source_chars: int = 0) -> str:
    """按笔记类型取对应的总结 Prompt 模板。

    Args:
        note_type: 笔记类型 key；未知类型安全回退到 structured。
        source_chars: 源文本字数；> 0 时追加按源长算好的篇幅目标块（覆盖优先）；
            > `extract_checklist.EXTRACT_MIN_CHARS` 时再追加「先列清单、再成文」两阶段指令
            （A4 清单内化，PLAN-20261018 §6 A4 / §12.3 #11-a；主路径无外部 provider，
            提取只能由执行模型在同一次派工里完成）；
            ≤ `section_budget.SHORT_SOURCE_MAX_CHARS` 时追加「短源篇幅取向」块，关停分析层
            与元层小节（PLAN-20261019-short-source-trim；长源不受影响）。

    新增笔记类型：在 NOTE_TEMPLATES 中加一项即可，无需改其他代码。
    """
    t = NOTE_TEMPLATES.get(note_type)
    if not t:
        t = NOTE_TEMPLATES["structured"]
    return (t["prompt"] + render_coverage_guide(source_chars, note_type)
            + render_extraction_rules(source_chars)
            + render_section_budget(source_chars, note_type))


