def format_note_with_prompt(content: str, author: str = "", url: str = "", tags: list = None, add_metadata: bool = True, publish_time: int = 0) -> str:
    """格式化笔记内容

    Args:
        content: 笔记正文内容
        author: 作者信息
        url: 原文链接
        tags: 标签列表
        add_metadata: 是否添加元数据（标签、作者、链接）
        publish_time: 内容原始发布时间（epoch 秒）；>0 时在元信息追加「发布时间」

    Returns:
        格式化后的笔记内容
    """
    tags = tags or []

    # F：统一元数据格式（把 `**标签**：xxx` 等非井号格式归一为 `#标签1 #标签2`）
    content = normalize_note_metadata(content)

    if add_metadata:
        # 去除 content 中可能残留的旧标签行（param tags 为权威，避免重复标签行）
        stripped_lines = []
        in_fence = False
        for line in content.split("\n"):
            if line.lstrip().startswith("```"):
                in_fence = not in_fence
                stripped_lines.append(line)
                continue
            if not in_fence and (_TAG_LINE_RE.match(line) or _HASHTAG_LINE_RE.match(line)):
                continue
            stripped_lines.append(line)
        content = "\n".join(stripped_lines)

        # 添加标签
        if tags:
            formatted = "#" + " #".join(tags) + "\n\n"
        else:
            formatted = ""

        # 来源链接 = formatter 单一权威写入（模板已禁止 LLM 在正文写来源链接）。
        # 这样每篇永远只有一个来源链接，且 URL 来自流水线 original_url（抓取真相）。
        # 若 LLM 仍写了作者/嘉宾行，则只补来源链接、避免双作者行。
        author_display = author if author else "【作者未知】"
        has_source_link = "**来源链接**" in content
        has_author_line = "**作者**" in content
        if not has_source_link:
            if url:
                if has_author_line:
                    formatted += f"**来源链接**：[原文链接]({url})\n\n"
                else:
                    formatted += f"**作者**：{author_display} | **来源链接**：[原文链接]({url})\n\n"
            else:
                if has_author_line:
                    formatted += "**来源链接**：【无来源链接】\n\n"
                else:
                    formatted += f"**作者**：{author_display} | **来源链接**：【无来源链接】\n\n"

        # 内容原始发布时间（若提供）：让笔记记录「内容何时发的」，而非仅记录我们处理时间
        if publish_time and publish_time > 0:
            pub_date = datetime.fromtimestamp(publish_time).strftime("%Y-%m-%d %H:%M")
            formatted += f"**发布时间**：{pub_date}\n\n"

        formatted += content
    else:
        formatted = content

    return formatted


# ---------------------------------------------------------------------------
# F：元数据格式归一（井号标签）
# ---------------------------------------------------------------------------
_TAG_LINE_RE = re.compile(r'^\s*\*{0,2}标签\*{0,2}\s*[：:]\s*(.+?)\s*$')
_HASHTAG_LINE_RE = re.compile(r'^\s*#\S+(?:\s+#\S+)*\s*$')  # 井号标签行：# 后无空格（区别 Markdown 标题），整行 token 均为 #xxx

def normalize_note_metadata(md: str) -> str:
    """把笔记里错误的标签行（`**标签**：xxx` / `标签：xxx`）归一为井号格式。

    - 识别 `**标签**：访谈笔记 · 创业 · 人生决策` 这类行；
    - 按 逗号/顿号/空格/中圆点/斜杠/竖线 切分为多个标签，每个前缀 `#`；
    - 去重；无标签可解析时丢弃该行（不保留错误格式）。
    - 不改其他元数据行（如 `**嘉宾**` / `**访谈者**`）。
    """
    if not md:
        return md
    lines = md.split("\n")
    out = []
    for line in lines:
        m = _TAG_LINE_RE.match(line)
        if m:
            raw = m.group(1).strip()
            parts = re.split(r'[,，、\s·/｜|]+', raw)
            tags = []
            for p in parts:
                p = p.strip().strip('#').strip()
                if p and p not in tags:
                    tags.append(p)
            if tags:
                out.append("#" + " #".join(tags))
                continue
            # 无可解析标签：丢弃错误格式行
            continue
        out.append(line)
    return "\n".join(out)


